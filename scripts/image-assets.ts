import { createHash } from "node:crypto";
import { readdir } from "node:fs/promises";
import { join } from "node:path";
import { format } from "prettier";
import type { ResponsiveImageAsset } from "../src/lib/images/responsive";

export const sourceHash = (buffer: Buffer): string =>
  createHash("sha256").update(buffer).digest("hex");
export const imageBudget = (width: number): number => (width <= 480 ? 180 : 450) * 1024;
export async function listImageSources(directory: string): Promise<string[]> {
  const files = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    files.map(async (file) =>
      file.isDirectory()
        ? listImageSources(join(directory, file.name))
        : /\.(jpe?g|png|webp|avif)$/i.test(file.name)
          ? [join(directory, file.name)]
          : [],
    ),
  );
  return nested.flat().sort();
}
export type ImageManifest = {
  version: 1;
  images: Record<
    string,
    {
      sourceHash: string;
      asset: ResponsiveImageAsset;
      variants: {
        path: string;
        width: number;
        height: number;
        format: "webp" | "avif";
        bytes: number;
      }[];
    }
  >;
};

export async function renderImageCatalogue(images: ImageManifest["images"]): Promise<string> {
  const frontend = Object.fromEntries(
    Object.entries(images).map(([key, value]) => [key, value.asset]),
  );
  return format(
    `// Generated by images:generate. Do not edit.\nimport type { ResponsiveImageAsset } from "./responsive";\nexport const LOCAL_IMAGE_ASSETS: Readonly<Record<string, ResponsiveImageAsset>> = ${JSON.stringify(frontend, null, 2)};\n`,
    { parser: "typescript", printWidth: 100 },
  );
}
